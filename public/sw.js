const CACHE_NAME = 'schools-garwolin-v1';
const STATIC_ASSETS = [
  '/',
  '/schools',
  '/admin',
  '/analytics',
  '/manifest.json',
  '/favicon.ico',
  '/hero.jpg',
  '/api/schools'
];

// Instalacja i zapisanie głównych zasobów w cache
self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => {
      return cache.addAll(STATIC_ASSETS).catch(() => {});
    })
  );
  self.skipWaiting();
});

// Czyszczenie starych wersji pamięci podręcznej
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(
        keys.map((key) => {
          if (key !== CACHE_NAME) {
            return caches.delete(key);
          }
        })
      )
    )
  );
  self.clients.claim();
});

// Strategia Network-First z automatycznym przełączeniem na Offline Cache
self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;

  event.respondWith(
    fetch(event.request)
      .then((networkResponse) => {
        const responseClone = networkResponse.clone();
        caches.open(CACHE_NAME).then((cache) => {
          cache.put(event.request, responseClone);
        });
        return networkResponse;
      })
      .catch(() => {
        return caches.match(event.request).then((cachedResponse) => {
          if (cachedResponse) return cachedResponse;
          if (event.request.mode === 'navigate') {
            return caches.match('/schools') || caches.match('/');
          }
        });
      })
  );
});